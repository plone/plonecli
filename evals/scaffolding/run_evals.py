@dataclass
class Step:
    args: list[str]
    cwd: Path


@dataclass
class Case:
    case_id: str
    category: str
    steps: list[Step]
    project: Path | None = None
    copy_from: Path | None = None
    coverage: dict[str, Any] = field(default_factory=dict)
    quick: bool = False


def slug(value: str) -> str:
    return "".join(ch if ch.isalnum() else "-" for ch in value.lower()).strip("-")


def audit_template_inventory() -> None:
    """Fail when a template is added without an explicit evaluation lane."""
    discovered = {path.parent.name for path in TEMPLATES.glob("*/copier.yml")}
    expected = {
        "addon",
        "backend_addon",
        "zope-setup",
        "zope_instance",
        *BACKEND_SUBTEMPLATES,
    }
    if discovered != expected:
        missing = sorted(discovered - expected)
        stale = sorted(expected - discovered)
        raise SystemExit(
            f"template inventory drift; add evaluation cases: "
            f"uncovered={missing}, missing={stale}"
        )


def data_args(data: dict[str, Any]) -> list[str]:
    result: list[str] = []
    for key, value in data.items():
        if isinstance(value, bool):
            value = str(value).lower()
        result.extend(["-d", f"{key}={value}"])
    return result


def create_step(template: str, target: Path, data: dict[str, Any]) -> Step:
    return Step(
        [
            "create",
            template,
            str(target),
            "--defaults",
            "--allow-dirty",
            "--no-git",
            *data_args(data),
        ],
        ROOT,
    )


def add_step(template: str, target: Path, data: dict[str, Any]) -> Step:
    # Options intentionally follow the positional template. This exercises the
    # chain=True/interspersed-argument behavior used in documentation.
    return Step(
        [
            "add",
            template,
            "--defaults",
            "--allow-dirty",
            "--no-git",
            *data_args(data),
        ],
        target,
    )


